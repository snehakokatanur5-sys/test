import { useState } from 'react';
import { PaperAnalysisData, TokenStats } from '../types';
import { X, Copy, Check, Download, FileText, Printer } from 'lucide-react';

interface ExportDossierModalProps {
  isOpen: boolean;
  onClose: () => void;
  data: PaperAnalysisData;
  tokenStats?: TokenStats;
}

export default function ExportDossierModal({
  isOpen,
  onClose,
  data,
  tokenStats,
}: ExportDossierModalProps) {
  const [copied, setCopied] = useState<boolean>(false);

  if (!isOpen) return null;

  const markdownContent = `# CS Research Analysis: ${data.paper.title}
**Authors:** ${data.paper.authors?.join(', ') || 'N/A'}
**Venue / Year:** ${data.paper.yearOrVenue || 'Recent'}
**URL:** ${data.paper.url || (data.paper.arxivId ? `https://arxiv.org/abs/${data.paper.arxivId}` : 'N/A')}
${tokenStats ? `**Token Efficiency:** ${tokenStats.totalTokens.toLocaleString()} / ${tokenStats.budgetLimit.toLocaleString()} tokens (${tokenStats.efficiencyPercent}% of budget)` : ''}

---

## 1. CORE CONCEPT EXTRACTION (<300 Words)

### Problem Statement
${data.coreConcept.problemStatement}

### Primary Methodology
${data.coreConcept.primaryMethodology}

### Key Mathematical & Algorithmic Breakthroughs
${data.coreConcept.keyBreakthroughs}

---

## 2. ARCHITECTURAL FLOWCHART (Mermaid.js)

\`\`\`mermaid
${data.mermaidFlowchart}
\`\`\`

---

## 3. FUTURE WORK & INTERNSHIP RESUME OPPORTUNITIES (3rd-Year CS Student)

${data.studentOpportunities.map((opp, i) => `### Idea #${i + 1}: ${opp.title}
* **The Exact Extension:** ${opp.extension}
* **Targeted Performance Metric:** ${opp.targetMetric}
* **Recommended Tech Stack:** ${opp.techStack.join(', ')}
* **Implementation Plan:** ${opp.implementationPlan}
* **Resume Bullet Formulation:**
  > "${opp.resumeBullet}"
`).join('\n')}

---
*Generated by CS Research Agent • Prioritizing System Architecture & Token Efficiency (<25k tokens)*
`;

  const handleCopy = async () => {
    await navigator.clipboard.writeText(markdownContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const slug = (data.paper.title || 'paper')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .slice(0, 35);
    const blob = new Blob([markdownContent], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${slug}-cs-research-dossier.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-xs">
      <div className="bg-white rounded-2xl border border-slate-200 shadow-2xl w-full max-w-3xl max-h-[85vh] flex flex-col overflow-hidden animate-in fade-in duration-200">
        <div className="px-6 py-4 border-b border-slate-200 bg-slate-50 flex items-center justify-between">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-indigo-600 text-white flex items-center justify-center font-bold">
              <FileText className="w-4 h-4" />
            </div>
            <div>
              <h3 className="font-bold text-slate-900 text-base">Export Academic Research Dossier</h3>
              <p className="text-xs text-slate-500">Markdown format compatible with GitHub, Obsidian, and Notion</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 hover:bg-slate-200 rounded-lg text-slate-400 hover:text-slate-700 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        <div className="flex-1 bg-slate-950 p-4 overflow-auto font-mono text-xs text-slate-200">
          <pre className="whitespace-pre-wrap leading-relaxed">{markdownContent}</pre>
        </div>

        <div className="px-6 py-3 border-t border-slate-200 bg-white flex items-center justify-between gap-3">
          <button
            onClick={handlePrint}
            className="flex items-center gap-1.5 text-xs font-medium text-slate-600 hover:text-slate-900 px-3 py-1.5 rounded-lg border border-slate-200 hover:bg-slate-50 transition"
          >
            <Printer className="w-4 h-4" />
            <span>Print / Save PDF</span>
          </button>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-100 hover:bg-slate-200 text-slate-700 text-xs font-medium transition"
            >
              {copied ? (
                <>
                  <Check className="w-4 h-4 text-emerald-600" />
                  <span className="text-emerald-700">Copied Markdown</span>
                </>
              ) : (
                <>
                  <Copy className="w-4 h-4 text-slate-500" />
                  <span>Copy Markdown</span>
                </>
              )}
            </button>
            <button
              onClick={handleDownload}
              className="flex items-center gap-1.5 px-4 py-1.5 rounded-lg bg-indigo-600 hover:bg-indigo-700 text-white text-xs font-semibold shadow-xs transition"
            >
              <Download className="w-4 h-4" />
              <span>Download .md</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
